from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum
from typing import Any

from app.domain.models.portfolio import Portfolio
from app.domain.rules.base import BaseRiskRule, RuleResult, Severity


class ComplianceStatus(str, Enum):
    """Overall portfolio risk compliance status."""

    COMPLIANT = "COMPLIANT"  # All deterministic rules passed
    WARNING = "WARNING"  # Passed with non-critical warnings
    NON_COMPLIANT = "NON_COMPLIANT"  # At least one critical rule failed


@dataclass(frozen=True)
class RiskAssessmentReport:
    """
    Immutable audit report generated by the RiskEngine (F1.7).
    Contains full snapshot of prices, ratios, and evaluation outcomes.
    """

    portfolio_id: str | None
    portfolio_name: str
    compliance_status: ComplianceStatus
    total_rules_evaluated: int
    passed_rules_count: int
    failed_rules_count: int
    critical_alerts_count: int
    warning_alerts_count: int
    results: list[RuleResult]
    evaluated_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    context_snapshot: dict[str, Any] = field(default_factory=dict)


class RiskEngine:
    """
    Deterministic Risk Engine Orchestrator.
    Evaluates a portfolio against a pluggable suite of BaseRiskRule instances (Strategy Pattern).
    Zero AI / 100% Deterministic Rule Engine.
    """

    def __init__(self, rules: list[BaseRiskRule] | None = None) -> None:
        self._rules: list[BaseRiskRule] = rules if rules is not None else []

    def register_rule(self, rule: BaseRiskRule) -> None:
        """Adds a rule to the active evaluation suite."""
        if not any(r.rule_id == rule.rule_id for r in self._rules):
            self._rules.append(rule)

    def unregister_rule(self, rule_id: str) -> None:
        """Removes a rule by its rule_id."""
        self._rules = [r for r in self._rules if r.rule_id != rule_id]

    def clear_rules(self) -> None:
        """Clears all registered rules."""
        self._rules.clear()

    @property
    def registered_rules(self) -> list[BaseRiskRule]:
        """Returns the list of currently registered rules."""
        return list(self._rules)

    def evaluate(
        self,
        portfolio: Portfolio,
        context: dict[str, Any] | None = None,
    ) -> RiskAssessmentReport:
        """
        Executes all registered rules against the provided portfolio.
        Returns a structured RiskAssessmentReport with full audit traceability.
        """
        ctx = context or {}
        all_results: list[RuleResult] = []

        for rule in self._rules:
            try:
                rule_results = rule.evaluate(portfolio=portfolio, context=ctx)
                all_results.extend(rule_results)
            except Exception as exc:
                # Catch rule-level execution exceptions to ensure engine fault tolerance
                all_results.append(
                    RuleResult(
                        rule_id=rule.rule_id,
                        rule_name=rule.rule_name,
                        passed=False,
                        severity=Severity.CRITICAL,
                        message=f"Error durante la evaluación de la regla: {str(exc)}",
                        details={"exception": str(exc)},
                    )
                )

        # Aggregate metrics
        total = len(all_results)
        passed = sum(1 for r in all_results if r.passed)
        failed = total - passed
        critical = sum(1 for r in all_results if not r.passed and r.severity == Severity.CRITICAL)
        warning = sum(1 for r in all_results if not r.passed and r.severity == Severity.WARNING)

        if critical > 0:
            status = ComplianceStatus.NON_COMPLIANT
        elif warning > 0:
            status = ComplianceStatus.WARNING
        else:
            status = ComplianceStatus.COMPLIANT

        return RiskAssessmentReport(
            portfolio_id=portfolio.id,
            portfolio_name=portfolio.name,
            compliance_status=status,
            total_rules_evaluated=total,
            passed_rules_count=passed,
            failed_rules_count=failed,
            critical_alerts_count=critical,
            warning_alerts_count=warning,
            results=all_results,
            context_snapshot=ctx,
        )
